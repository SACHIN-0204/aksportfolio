import { Router } from "express";
import { createProduct, deleteProduct, getProduct, listAllProducts, listCategories, listProducts, updateProduct } from "../controllers/productController.js";
import { requireAdmin } from "../middleware/authMiddleware.js";
import { asyncHandler as h } from "../middleware/asyncHandler.js";
import { validateId } from "../middleware/validateId.js";
const router = Router();
router.get("/", h(listProducts));
router.get("/categories", h(listCategories));
router.get("/admin/all", requireAdmin, h(listAllProducts));
router.get("/:id", validateId, h(getProduct));
router.post("/", requireAdmin, h(createProduct));
router.put("/:id", requireAdmin, validateId, h(updateProduct));
router.delete("/:id", requireAdmin, validateId, h(deleteProduct));
export default router;
